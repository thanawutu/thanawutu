"""Generate soar/imperva_ioc_block_global_code.py = imperva_lib.py + vt_lib.py + imperva_soar_handler.py

Paste the generated file into the SOAR playbook's *Global Custom Code*.
Run:  python3 soar/build_global_code.py
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
LIB = os.path.join(HERE, "..", "TA-imperva-ioc-block", "bin", "imperva_lib.py")
VTLIB = os.path.join(HERE, "..", "TA-imperva-ioc-block", "bin", "vt_lib.py")
HANDLER = os.path.join(HERE, "imperva_soar_handler.py")
OUT = os.path.join(HERE, "imperva_ioc_block_global_code.py")
OUT_BLOCK = os.path.join(HERE, "imperva_ioc_block_code_block.py")
OUT_PLAYBOOK = os.path.join(HERE, "imperva_ioc_block_playbook.py")


def build():
    lib = open(LIB).read()
    vtlib = open(VTLIB).read()
    handler = open(HANDLER).read()
    handler = re.sub(r"# --- BEGIN LIB IMPORT.*?# --- END LIB IMPORT ---\n",
                     "import json\nimport os\n", handler, flags=re.S)
    head = ("# GENERATED FILE - do not edit. Source: imperva_lib.py + vt_lib.py + imperva_soar_handler.py\n"
            "# Rebuild with: python3 soar/build_global_code.py\n"
            "# Paste ALL of this into the SOAR playbook > Global Custom Code.\n\n")
    return head + "# " + "=" * 74 + "\n# imperva_lib\n# " + "=" * 74 + "\n" + lib + \
        "\n\n# " + "=" * 74 + "\n# vt_lib\n# " + "=" * 74 + "\n" + vtlib + \
        "\n\n# " + "=" * 74 + "\n# SOAR handler\n# " + "=" * 74 + "\n" + handler


def build_code_block():
    """
    Variant for playbook editors without a Global Custom Code section (SOAR 8.x VPE).
    Paste it between "## Custom Code Start" and "## Custom Code End" of code_1.

    The library is carried as a raw string and compiled with exec(), so the
    indentation of the pasted lines does not matter (textwrap.dedent removes any
    indentation the editor adds). Only the 6 short lines outside the string sit
    inside code_1 and need its 4-space indent.
    """
    src = build()
    assert "'''" not in src, "library source must not contain triple single quotes"
    return "\n".join([
        "    # ===== Imperva IOC block (Splunk <-> SOAR <-> Imperva / VirusTotal) =====",
        "    # GENERATED by soar/build_global_code.py - paste ALL of this between",
        "    # '## Custom Code Start' and '## Custom Code End' of code_1.",
        "    import textwrap as _tw",
        "    _IMPERVA_SRC = r'''",
        src,
        "'''",
        "    _imperva_ns = {\"__name__\": \"imperva_ioc_block_lib\"}",
        "    exec(compile(_tw.dedent(_IMPERVA_SRC), \"imperva_ioc_block_lib\", \"exec\"), _imperva_ns)",
        "    _imperva_ns[\"imperva_soar_handle\"](container, phantom)",
        "",
    ])


PLAYBOOK_TEMPLATE = '''"""
Imperva IOC block - Splunk SOAR 8.x playbook (label: imperva_ioc_block)
GENERATED by soar/build_global_code.py
"""


import phantom.rules as phantom
import json
from datetime import datetime, timedelta


@phantom.playbook_block()
def on_start(container):
    phantom.debug('on_start() called')

    # call 'code_1' block
    code_1(container=container)

    return

@phantom.playbook_block()
def code_1(action=None, success=None, container=None, results=None, handle=None, filtered_artifacts=None, filtered_results=None, custom_function=None, loop_state_json=None, **kwargs):
    phantom.debug("code_1() called")

    ################################################################################
    ## Custom Code Start
    ################################################################################

%(block)s
    ################################################################################
    ## Custom Code End
    ################################################################################

    phantom.save_block_result(key="code_1_called", value="True")

    return


@phantom.playbook_block()
def on_finish(container, summary):
    phantom.debug("on_finish() called")

    ################################################################################
    ## Custom Code Start
    ################################################################################

    # Write your custom code here...

    ################################################################################
    ## Custom Code End
    ################################################################################

    return
'''


def build_playbook():
    """The whole SOAR 8.x playbook file with the code block already filled in."""
    return PLAYBOOK_TEMPLATE.replace("%(block)s", build_code_block())


if __name__ == "__main__":
    with open(OUT, "w") as f:
        f.write(build())
    with open(OUT_BLOCK, "w") as f:
        f.write(build_code_block())
    with open(OUT_PLAYBOOK, "w") as f:
        f.write(build_playbook())
    print("wrote", OUT)
    print("wrote", OUT_BLOCK)
    print("wrote", OUT_PLAYBOOK)
